let randomState = 20261104;
function random(){
    randomState = ( randomState * 1103515245 + 12345 ) % 2147483648;
    return randomState / 2147483648;
}
const randInt = ( min: number, max: number ) => min + Math.floor( random() * ( max - min + 1 ) );
const pick = <T>( list: readonly T[] ): T => list[ Math.floor( random() * list.length ) ];
function shuffle<T>( list: readonly T[] ): T[] {
    const copy = [ ...list ];
    for( let i = copy.length - 1; i > 0; i-- ){
        const j = Math.floor( random() * ( i + 1 ) );
        [ copy[i], copy[j] ] = [ copy[j], copy[i] ];
    }
    return copy;
}
const sample = <T>( list: readonly T[], n: number ) => shuffle( list ).slice( 0, Math.max( 0, Math.min( n, list.length ) ) );

