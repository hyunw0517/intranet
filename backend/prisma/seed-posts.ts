const NOW = new Date();
const HOUR = 60 * 60 * 1000;
const KST = 9 * HOUR;

// 최근 DAYS일 중 하루 + 업무시간(KST 9~19시 위주). 주말은 70% 확률로 다시 고른다.
function randomPostDate( today = false ): Date {
    for( let i = 0; i < 10; i++ ){
        const daysAgo = today ? 0 : randInt( 0, DAYS - 1 );
        const kstMidnight = Math.floor( ( NOW.getTime() + KST ) / ( 24 * HOUR ) ) * 24 * HOUR - KST;
        const day = new Date( kstMidnight - daysAgo * 24 * HOUR );
        const weekday = new Date( day.getTime() + KST ).getUTCDay();
        if( !today && ( weekday === 0 || weekday === 6 ) && random() < 0.7 ) continue;
        const hour = random() < 0.85 ? randInt( 9, 18 ) : randInt( 7, 22 );
        const at = new Date( day.getTime() + hour * HOUR + randInt( 0, 59 ) * 60 * 1000 + randInt( 0, 59 ) * 1000 );
        if( at < NOW ) return at;
    }
    return new Date( NOW.getTime() - randInt( 1, 6 ) * HOUR );
}

// 기준 시각 이후, 최대 maxHours 안의 시각 (지금을 넘지 않게)
function after( base: Date, maxHours: number ): Date {
    const limit = Math.min( base.getTime() + maxHours * HOUR, NOW.getTime() );
    return new Date( base.getTime() + random() * Math.max( limit - base.getTime(), 60 * 1000 ) );
}

// after와 같지만 KST 8~21시 밖이면 다음 날 업무시간(9~18시)으로 옮긴다. (지금을 넘으면 원래 값)
function afterInWorkHours( base: Date, maxHours: number ): Date {
    const at = after( base, maxHours );
    const hour = new Date( at.getTime() + KST ).getUTCHours();
    if( hour >= 8 && hour < 21 ) return at;
    const kstMidnight = Math.floor( ( at.getTime() + KST ) / ( 24 * HOUR ) ) * 24 * HOUR - KST;
    const nextDay = kstMidnight + ( hour >= 21 ? 24 * HOUR : 0 );
    const moved = new Date( nextDay + randInt( 9, 17 ) * HOUR + randInt( 0, 59 ) * 60 * 1000 );
    return moved > base && moved < NOW ? moved : at;
}

const kstDate = ( d: Date ) => new Date( d.getTime() + KST ).toISOString().slice( 0, 10 );
const kstMonthDay = ( d: Date ) => { const s = kstDate( d ); return `${ Number( s.slice( 5, 7 ) ) }월 ${ Number( s.slice( 8, 10 ) ) }일`; };

