// ── 대상 게시판 ─────────────────────────────────────────────────────────
// 이름 → 종류·개수. 부서 게시판(이름에 '/' 또는 '(전체)')은 아래에서 따로 4개씩 배정한다.
const BOARD_PLAN: { name: string; kind: Kind; count: number; templates: Template[] }[] = [
    { name: '전체 공지', kind: 'notice', count: 14, templates: NOTICE },
    { name: '회사 규정', kind: 'rule', count: 8, templates: RULE },
    { name: '자료실', kind: 'archive', count: 12, templates: ARCHIVE },
    { name: '임원진', kind: 'exec', count: 5, templates: EXEC },
    { name: '헬프데스크', kind: 'help', count: 20, templates: HELP },
    { name: '인사 문의', kind: 'hr', count: 13, templates: HR_QUESTION },
    { name: '자유게시판', kind: 'free', count: 36, templates: FREE },
];
const TEAM_POSTS_PER_BOARD = 4;
const TODAY_POSTS = 6; // 목록의 "오늘 HH:mm" 표시 확인용

interface Member { id: number; role: UserRole }
interface PlannedPost { boardId: number; boardName: string; kind: Kind; template: Template; team: string }

async function main(){
    const boards = await prisma.board.findMany({
        select: { id: true, name: true, type: true },
        where: { deleted: false, type: { in: [ BoardType.NORMAL, BoardType.NOTICE, BoardType.ALBUM ] } },
        orderBy: { id: 'asc' },
    });
    const boardByName = new Map( boards.map( ( b ) => [ b.name, b ] ) );

    // 1. 게시판별 글 배정
    const plans: PlannedPost[] = [];
    for( const plan of BOARD_PLAN ){
        const board = boardByName.get( plan.name );
        if( !board ){ console.log( `- 게시판 없음, 건너뜀: ${ plan.name }` ); continue; }
        const templates = shuffle( plan.templates ).slice( 0, plan.count );
        for( const template of templates ){
            plans.push({ boardId: board.id, boardName: board.name, kind: plan.kind, template, team: '' });
        }
    }
    for( const board of boards.filter( ( b ) => b.name.includes( '/' ) || b.name.endsWith( '(전체)' ) ) ){
        // "경영지원본부/인사팀" → 인사팀, "기술본부/본부"·"기술본부(전체)" → 기술본부
        const [ head, tail ] = board.name.replace( '(전체)', '' ).split( '/' );
        const team = !tail || tail === '본부' ? head : tail;
        const keyword = Object.keys( TEAM_SPECIFIC ).find( ( k ) => ( tail ?? '본부' ).includes( k ) );
        const specific = keyword ? sample( TEAM_SPECIFIC[ keyword ], 2 ) : [];
        const common = sample( TEAM_COMMON, TEAM_POSTS_PER_BOARD - specific.length );
        for( const template of [ ...specific, ...common ] ){
            plans.push({ boardId: board.id, boardName: board.name, kind: 'team', template, team });
        }
    }
    const targetBoardIds = [ ...new Set( plans.map( ( p ) => p.boardId ) ) ];

    // 2. 회원별 권한 (서비스의 판정 로직 그대로)
    const members: Member[] = await prisma.users.findMany({
        select: { id: true, role: true },
        where: { deleted: false, status: UserStatus.ACTIVE, role: { in: [ UserRole.USER, UserRole.ADMIN ] } },
        orderBy: { id: 'asc' },
    });
    const permOf = new Map<string, BoardPermission>(); // `${boardId}:${userId}`
    for( const boardId of targetBoardIds ){
        await Promise.all( members.map( async ( m ) => {
            try {
                const { perm } = await boardAuthService.assertBoardPermission( boardId, m, 'read' );
                permOf.set( `${ boardId }:${ m.id }`, perm );
            } catch( e ){
                if( !( e instanceof NotFoundException ) ) throw e; // 읽기 권한 없음(404)만 무시
            }
        } ) );
    }
    const usersWith = ( boardId: number, action: keyof BoardPermission ) =>
        members.filter( ( m ) => permOf.get( `${ boardId }:${ m.id }` )?.[ action ] );

    // 쓸 수 있는 사람이 없는 게시판의 글은 뺀다.
    const writable = plans.filter( ( p ) => usersWith( p.boardId, 'write' ).length > 0 );
    const skipped = [ ...new Set( plans.filter( ( p ) => !writable.includes( p ) ).map( ( p ) => p.boardName ) ) ];

    console.log( `대상 게시판 ${ targetBoardIds.length }개, 게시글 ${ writable.length }개 (회원 ${ members.length }명 권한 판정)` );
    if( skipped.length ) console.log( `- 쓰기 권한자가 없어 건너뜀: ${ skipped.join( ', ' ) }` );
    if( DRY_RUN ){
        for( const boardId of targetBoardIds ){
            const name = boards.find( ( b ) => b.id === boardId )!.name;
            console.log( `  ${ name.padEnd( 16 ) } 글 ${ writable.filter( ( p ) => p.boardId === boardId ).length }개 · 쓰기 ${ usersWith( boardId, 'write' ).length }명 · 댓글 ${ usersWith( boardId, 'comment' ).length }명 · 읽기 ${ usersWith( boardId, 'read' ).length }명` );
        }
        return;
    }

    // 3. 이미 글이 있으면 중단 (--reset이면 지우고 진행)
    const existing = await prisma.post.count({ where: { boardId: { in: targetBoardIds } } });
    if( existing > 0 && !RESET ){
        console.log( `대상 게시판에 게시글이 ${ existing }개 있어 중단합니다. 지우고 다시 만들려면 --reset` );
        return;
    }

    // 작성 당시 소속 (회원별 1회 조회)
    const orgCache = new Map<number, Awaited<ReturnType<OrganizationService['getPrimaryOrganizationNames']>>>();
    const orgOf = async ( userId: number ) => {
        if( !orgCache.has( userId ) ) orgCache.set( userId, await organizationService.getPrimaryOrganizationNames( userId ) );
        return orgCache.get( userId )!;
    };
    for( const m of members ) await orgOf( m.id );

    // 날짜 배정 (오늘 글 몇 개 + 나머지는 최근 30일)
    const dated = shuffle( writable ).map( ( plan, i ) => ({ plan, at: randomPostDate( i < TODAY_POSTS ) }) )
        .sort( ( a, b ) => a.at.getTime() - b.at.getTime() );   // id 순서 = 작성 순서

    const summary = { posts: 0, comments: 0, deletedComments: 0, likes: 0, views: 0 };

    await prisma.$transaction( async ( tx ) => {
        if( existing > 0 ){
            const postIds = ( await tx.post.findMany({ select: { id: true }, where: { boardId: { in: targetBoardIds } } }) ).map( ( p ) => p.id );
            await tx.comment.updateMany({ where: { postId: { in: postIds } }, data: { parentCommentId: null } }); // 자기 참조 FK
            await tx.comment.deleteMany({ where: { postId: { in: postIds } } });
            await tx.postLike.deleteMany({ where: { postId: { in: postIds } } });
            await tx.postView.deleteMany({ where: { postId: { in: postIds } } });
            await tx.post.deleteMany({ where: { id: { in: postIds } } });
            console.log( `- 기존 게시글 ${ postIds.length }개 삭제 (--reset)` );
        }

        for( const { plan, at } of dated ){
            const author = pick( usersWith( plan.boardId, 'write' ) );
            const names = await orgOf( author.id );
            const ctx: Ctx = { team: plan.team, at };
            const { html: content, text: contentText } = sanitizeEditorHtml( plan.template.body( ctx ) );
            const activity = ACTIVITY[ plan.kind ];

            // 조회·좋아요 (작성자 제외, 읽기 권한자 중에서)
            const readers = usersWith( plan.boardId, 'read' ).filter( ( m ) => m.id !== author.id );
            const freshness = Math.min( 1, ( NOW.getTime() - at.getTime() ) / ( 7 * 24 * HOUR ) + 0.2 ); // 오래된 글일수록 많이 봄
            const viewers = sample( readers, Math.round( readers.length * activity.viewRate * freshness * ( 0.5 + random() ) ) );
            const likers = sample( viewers, Math.round( viewers.length * activity.likeRate * ( 0.5 + random() * 1.5 ) ) );
            // 조회수는 열람할 때마다 오른다(같은 사람이 다시 봐도 +1). 고유 열람자 수에 다시 본 횟수를 더한다.
            const viewCount = viewers.length + Math.round( viewers.length * random() * 0.4 );

            const post = await tx.post.create({
                data: {
                    boardId: plan.boardId,
                    authorId: author.id,
                    authorDepartmentName: names.departmentName,
                    authorPositionName: names.positionName,
                    authorJobTitleName: names.jobTitleName,
                    title: plan.template.title( ctx ),
                    content,
                    contentText,
                    viewCount,
                    likeCount: likers.length,
                    createdAt: at,
                    createdId: author.id,
                    updatedAt: at,
                    updatedId: author.id,
                },
            });
            summary.posts++;

            if( viewers.length ){
                await tx.postView.createMany({ data: viewers.map( ( v ) => ({ postId: post.id, userId: v.id, viewedAt: after( at, 72 ) }) ) });
                summary.views += viewers.length;
            }
            if( likers.length ){
                await tx.postLike.createMany({ data: likers.map( ( l ) => ({ postId: post.id, userId: l.id, createdAt: after( at, 96 ) }) ) });
                summary.likes += likers.length;
            }

            // 댓글: 글별 댓글(COMMENTS_BY_TITLE)이 있으면 그 문장을 순서대로, 없으면 종류별 기본 문장을 섞어서 쓴다.
            // 같은 글에서 같은 문장이 반복되지 않게 한 번씩만 쓰고, 일부는 답글로 단다. 작성 시각은 글 이후 순서대로(업무시간 위주).
            const commenters = usersWith( plan.boardId, 'comment' );
            if( !commenters.length ) continue;
            const title = plan.template.title( ctx );
            const specific = COMMENTS_BY_TITLE[ title ];
            const pool = specific ?? shuffle( COMMENTS[ plan.kind ] );
            const [ minCount, maxCount ] = activity.comments;
            const topCount = Math.min( pool.length, specific ? randInt( Math.max( minCount, 1 ), pool.length ) : randInt( minCount, maxCount ) );
            const replyCount = topCount ? randInt( 0, Math.ceil( topCount / 2 ) ) : 0;
            const authorCanComment = commenters.some( ( c ) => c.id === author.id );
            const created: { id: number; at: Date; authorId: number; text: string; hasReply: boolean }[] = [];
            let cursor = at;
            let top = 0;
            let replies = 0;
            while( top < topCount || replies < replyCount ){
                const asReply = created.length > 0 && replies < replyCount && ( top >= topCount || random() < 0.4 );
                const parent = asReply ? pick( created ) : null;
                // 질문(물음표) 댓글에는 글쓴이가 답하고, 그 외 답글도 글쓴이가 다는 경우가 많다.
                const isQuestion = !!parent && parent.text.trim().endsWith( '?' ) && parent.authorId !== author.id && authorCanComment;
                const writer = isQuestion || ( parent && authorCanComment && parent.authorId !== author.id && random() < 0.6 )
                    ? author
                    : pick( commenters.filter( ( c ) => c.id !== parent?.authorId ) );
                const text = !parent ? pool[ top ] : isQuestion ? pick( ANSWER_REPLIES[ plan.kind ] ) : pick( REPLIES[ plan.kind ] );
                cursor = afterInWorkHours( cursor, 18 );
                const n = await orgOf( writer.id );
                const row = await tx.comment.create({
                    data: {
                        postId: post.id,
                        parentCommentId: parent?.id ?? null,
                        authorId: writer.id,
                        authorDepartmentName: n.departmentName,
                        authorPositionName: n.positionName,
                        authorJobTitleName: n.jobTitleName,
                        comment: text,
                        createdAt: cursor,
                        createdId: writer.id,
                        updatedAt: cursor,
                        updatedId: writer.id,
                    },
                });
                if( parent ){ parent.hasReply = true; replies++; } else { top++; }
                created.push({ id: row.id, at: cursor, authorId: writer.id, text, hasReply: false });
                summary.comments++;
            }

            // 답글이 달린 댓글 일부를 삭제 처리 → 화면에 "(삭제된 댓글입니다)" 자리로 남는다.
            for( const c of created.filter( ( c ) => c.hasReply ) ){
                if( random() < 0.15 ){
                    const deletedAt = after( c.at, 24 );
                    await tx.comment.update({
                        where: { id: c.id },
                        data: { deleted: true, deletedAt, deletedId: c.authorId, updatedAt: deletedAt, updatedId: c.authorId },
                    });
                    summary.deletedComments++;
                }
            }
        }
    }, { timeout: 5 * 60 * 1000, maxWait: 10 * 1000 } );

    console.log( `완료: 게시글 ${ summary.posts }개, 댓글 ${ summary.comments }개(삭제 표시 ${ summary.deletedComments }개), 좋아요 ${ summary.likes }개, 조회 기록 ${ summary.views }개` );
}

main()
    .catch( ( e ) => { console.error( e ); process.exitCode = 1; } )
    .finally( () => prisma.$disconnect() );
